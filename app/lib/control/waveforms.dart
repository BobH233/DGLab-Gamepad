class PulseSample {
  final int frequency;
  final int strength;
  const PulseSample(this.frequency, this.strength);
}

class Waveform {
  final String id;
  final String name;
  final List<String> pulseData;
  final List<PulseSample> samples;

  Waveform(this.id, this.name, List<String> pulseData)
    : pulseData = List.unmodifiable(pulseData),
      samples = List.unmodifiable(_decode(pulseData));
}

List<PulseSample> _decode(List<String> frames) {
  final result = <PulseSample>[];
  for (final frame in frames) {
    if (frame.length != 16) {
      throw const FormatException('Invalid DG-LAB pulse frame');
    }
    final bytes = [
      for (var i = 0; i < 8; i++)
        int.parse(frame.substring(i * 2, i * 2 + 2), radix: 16),
    ];
    result.addAll(decodePulseBytes(bytes));
  }
  return result;
}

List<PulseSample> decodePulseBytes(List<int> bytes) {
  if (bytes.length != 8) {
    throw const FormatException('Invalid DG-LAB pulse frame');
  }
  return [
    for (var i = 0; i < 4; i++)
      PulseSample(decodeWaveformFrequency(bytes[i]), bytes[i + 4]),
  ];
}

int decodeWaveformFrequency(int value) {
  if (value == 0) return 0;
  if (value < 10) return 10;
  if (value <= 100) return value;
  if (value <= 200) return (value - 100) * 5 + 100;
  if (value <= 240) return (value - 200) * 10 + 600;
  return 0;
}

